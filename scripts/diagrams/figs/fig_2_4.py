"""Figure 2.4: Feathers's legacy change algorithm, five steps, as applied to Encore's barcode issuer."""
from dg import Diagram
from registry import figure


@figure
def fig_2_4():
    d = Diagram("fig-2-4", 864, 312, "The legacy change algorithm",
                "Five steps in order, left to right, as the Inventory and Resale teams applied them to the barcode "
                "issuer between months four and nine. 1, identify the change points: issuing a ticket to a new "
                "holder, revoking the old identity, and recording both in TicketIssued events. 2, find the test "
                "points: one pinch point, the method every issue variant finally calls to build and persist a "
                "ticket. 3, break dependencies: the issuer read the clock, the secret store and the event-code "
                "table directly, and each became a constructor parameter. 4, write tests: a characterization "
                "suite of 1,400 cases, most generated by replaying a year of issuance requests. 5, only then "
                "change and refactor: Reissue sprouted beside the issuer, and the issue variants collapse behind "
                "it later, as debt item INV-DEBT-017. Steps 3 and 4, highlighted, took most of the effort; the "
                "change itself was small. A note marks step 5 as where the instinct says to begin.")
    W, H, GAP, X0, Y = 144, 64, 28, 16, 72
    steps = [
        ("1 · IDENTIFY", "Change points", "backend",
         ["issue to a new holder;", "revoke the old identity;", "record both in", "TicketIssued events"]),
        ("2 · FIND", "Test points", "backend",
         ["one pinch point: the", "method every issue", "variant finally calls", "to build and persist"]),
        ("3 · BREAK", "Dependencies", "focal",
         ["clock, secret store and", "event-code table, read", "directly, each became a", "constructor parameter"]),
        ("4 · WRITE", "Tests", "focal",
         ["characterization suite", "of 1,400 cases, most", "from a replayed year", "of issuance requests"]),
        ("5 · ONLY THEN", "Change, refactor", "backend",
         ["Reissue sprouted beside", "the issuer; the issue", "variants collapse", "behind it later"]),
    ]
    xs = [X0 + i * (W + GAP) for i in range(5)]
    d.extra.append('<text class="dg-eyebrow" x="24" y="32" style="text-anchor:start">'
                   'BARCODE ISSUER · MONTHS 4–9 · READ LEFT TO RIGHT</text>')
    for a, b in zip(xs, xs[1:]):
        d.path([(a + W, Y + H // 2), (b, Y + H // 2)])
    for x, (tag, name, kind, lines) in zip(xs, steps):
        d.node(x, Y, W, H, name, None, kind, tag=tag)
        for i, line in enumerate(lines):
            d.note(x + 4, Y + H + 20 + i * 14, line)
    d.note(xs[4] + 4, Y + H + 20 + 4 * 14, "(INV-DEBT-017)")
    # where the instinct begins
    d.note(xs[4] + W // 2, Y - 12, "THE INSTINCT: START HERE", anchor="middle")
    # bracket under steps 3 and 4
    by = Y + H + 104
    l, r = xs[2] + 4, xs[3] + W - 4
    d.zones.append(f'<path class="dg-ill-soft" d="M {l},{by - 6} v 6 H {r} v -6"/>')
    d.label_at("MOST OF THE EFFORT", (l + r) / 2, by - 6, horizontal=True, side="below")
    by5 = by
    l5, r5 = xs[4] + 4, xs[4] + W - 4
    d.zones.append(f'<path class="dg-ill-soft" d="M {l5},{by5 - 6} v 6 H {r5} v -6"/>')
    d.label_at("A SMALL CHANGE", (l5 + r5) / 2, by5 - 6, horizontal=True, side="below")
    d.legend([("focal", "Where the effort went"), ("backend", "Step"), ("arrow:muted", "In this order")])
    return d
